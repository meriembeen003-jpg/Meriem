export function matchRootSourceByUrl(
  url: string | undefined,
  sources: RootSource[]
): RootSource | undefined {
  if (!url) return undefined;
  try {
    const parsed = new URL(url.startsWith("http") ? url : `https://${url}`);
    const host = parsed.hostname.toLowerCase().replace(/^www\./, "");
    return sources.find(
      (s) =>
        host === s.officialDomain.toLowerCase() ||
        host.endsWith(`.${s.officialDomain.toLowerCase()}`)
    );
  } catch {
    return undefined;
  }
}
